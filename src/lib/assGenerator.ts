import {
  DEFAULT_SUBTITLE_SETTINGS,
  resolveEffectiveStyle,
  SIZE_MULTIPLIERS,
} from "@/lib/styles";
import { SubtitleCue, SubtitleSettings } from "@/types/subtitle";

export interface AssGenerationOptions {
  width: number;
  height: number;
  settings: SubtitleSettings;
}

/**
 * Converts a #RRGGBB hex color into ASS Style &HAABBGGRR format (alpha: 00 opaque, FF transparent).
 */
export function hexToAssColor(hex: string, alphaHex = "00"): string {
  const clean = hex.replace(/^#/, "").trim();
  if (!/^[0-9a-fA-F]{6}$/.test(clean)) {
    return `&H${alphaHex}FFFFFF`;
  }
  const rr = clean.slice(0, 2).toUpperCase();
  const gg = clean.slice(2, 4).toUpperCase();
  const bb = clean.slice(4, 6).toUpperCase();
  return `&H${alphaHex.toUpperCase()}${bb}${gg}${rr}`;
}

/**
 * Converts a #RRGGBB hex color into inline ASS override color &HBBGGRR&.
 */
export function hexToAssInlineColor(hex: string): string {
  const clean = hex.replace(/^#/, "").trim();
  if (!/^[0-9a-fA-F]{6}$/.test(clean)) {
    return "&HFFFFFF&";
  }
  const rr = clean.slice(0, 2).toUpperCase();
  const gg = clean.slice(2, 4).toUpperCase();
  const bb = clean.slice(4, 6).toUpperCase();
  return `&H${bb}${gg}${rr}&`;
}

/**
 * Formats seconds into ASS timestamp H:MM:SS.cc (centiseconds).
 */
export function formatAssTime(sec: number): string {
  const safe = Math.max(0, sec);
  const totalCentis = Math.round(safe * 100);
  const centis = totalCentis % 100;
  const totalSeconds = Math.floor(totalCentis / 100);
  const seconds = totalSeconds % 60;
  const totalMinutes = Math.floor(totalSeconds / 60);
  const minutes = totalMinutes % 60;
  const hours = Math.floor(totalMinutes / 60);
  return `${hours}:${String(minutes).padStart(2, "0")}:${String(seconds).padStart(2, "0")}.${String(centis).padStart(2, "0")}`;
}

export function escapeAssText(text: string): string {
  return text
    .replace(/\\/g, "\\\\")
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/\r?\n/g, "\\N");
}

function getAlignmentAndMarginV(
  position: SubtitleSettings["position"],
  width: number,
  height: number
): { alignment: number; marginV: number } {
  const isPortrait = height > width;
  switch (position) {
    case "top":
      return {
        alignment: 8,
        marginV: Math.max(24, Math.round(height * (isPortrait ? 0.12 : 0.09))),
      };
    case "center":
      return { alignment: 5, marginV: 0 };
    case "bottom":
    default:
      return {
        alignment: 2,
        marginV: Math.max(28, Math.round(height * (isPortrait ? 0.17 : 0.11))),
      };
  }
}

export function computeBaseFontSize(
  width: number,
  height: number,
  size: SubtitleSettings["size"]
): number {
  const minDim = Math.max(320, Math.min(width, height));
  return Math.max(24, Math.round(minDim * 0.084 * SIZE_MULTIPLIERS[size]));
}

/**
 * Generates a complete Advanced Substation Alpha (.ass) subtitle document
 * with per-word highlighting and visual parity for all 3 FreeClips styles + Pro overrides.
 */
export function generateAssSubtitles(
  cues: SubtitleCue[],
  options?: Partial<AssGenerationOptions>
): string {
  const width = Math.max(240, Math.round(options?.width ?? 1080));
  const height = Math.max(240, Math.round(options?.height ?? 1920));
  const settings = options?.settings ?? DEFAULT_SUBTITLE_SETTINGS;
  const effective = resolveEffectiveStyle(settings);

  const fontSize = computeBaseFontSize(width, height, settings.size);
  const marginH = Math.max(24, Math.round(width * 0.07));
  const { alignment, marginV } = getAlignmentAndMarginV(
    settings.position,
    width,
    height
  );
  const boldFlag = effective.assBold ? -1 : 0;

  const baseHex = effective.baseColorHex;
  const activeHex = effective.activeColorHex;
  const outlineHex = effective.outlineColorHex;
  const glowHex = effective.glowColorHex;

  const lines: string[] = [
    "[Script Info]",
    "; Script generated by FreeClips (100% browser-side)",
    "ScriptType: v4.00+",
    `PlayResX: ${width}`,
    `PlayResY: ${height}`,
    "ScaledBorderAndShadow: yes",
    "WrapStyle: 2",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
  ];

  if (settings.styleId === "tiktok") {
    const outline = Math.max(3, Number((fontSize * 0.11).toFixed(1)));
    const shadow = Math.max(2, Number((fontSize * 0.05).toFixed(1)));
    lines.push(
      `Style: Main,${effective.assFontName},${fontSize},${hexToAssColor(activeHex)},${hexToAssColor(baseHex)},${hexToAssColor(outlineHex)},${hexToAssColor("#000000", "40")},${boldFlag},0,0,0,100,100,0.5,0,1,${outline},${shadow},${alignment},${marginH},${marginH},${marginV},1`
    );
  } else if (settings.styleId === "minimal") {
    const outline = Math.max(1.5, Number((fontSize * 0.032).toFixed(1)));
    const shadow = Math.max(1.5, Number((fontSize * 0.042).toFixed(1)));
    lines.push(
      `Style: Main,${effective.assFontName},${fontSize},${hexToAssColor(activeHex)},${hexToAssColor(baseHex)},${hexToAssColor(outlineHex, "55")},${hexToAssColor(outlineHex, "55")},${boldFlag},0,0,0,100,100,0,0,1,${outline},${shadow},${alignment},${marginH},${marginH},${marginV},1`
    );
  } else {
    const glowOutline = Math.max(4, Number((fontSize * 0.12).toFixed(1)));
    const coreOutline = Math.max(1.2, Number((fontSize * 0.028).toFixed(1)));
    lines.push(
      `Style: NeonGlow,${effective.assFontName},${fontSize},${hexToAssColor(outlineHex, "35")},${hexToAssColor(outlineHex, "35")},${hexToAssColor(outlineHex, "50")},${hexToAssColor("#000000", "FF")},${boldFlag},0,0,0,100,100,0.4,0,1,${glowOutline},0,${alignment},${marginH},${marginH},${marginV},1`
    );
    lines.push(
      `Style: NeonCore,${effective.assFontName},${fontSize},${hexToAssColor("#FFFFFF")},${hexToAssColor(baseHex)},${hexToAssColor(outlineHex)},${hexToAssColor("#000000", "FF")},${boldFlag},0,0,0,100,100,0.4,0,1,${coreOutline},0,${alignment},${marginH},${marginH},${marginV},1`
    );
  }

  lines.push(
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"
  );

  const validCues = cues.filter((c) => c.text.trim().length > 0 && c.end > c.start);
  const transformWord = (text: string) =>
    settings.uppercase ? text.toUpperCase() : text;

  for (const cue of validCues) {
    const words = cue.words.filter((w) => w.text.trim().length > 0);
    const shouldHighlightWords = settings.highlightActiveWord && words.length > 0;

    if (!shouldHighlightWords) {
      const content = escapeAssText(transformWord(cue.text.trim()));
      const startStr = formatAssTime(cue.start);
      const endStr = formatAssTime(cue.end);
      if (settings.styleId === "neon") {
        const blur = Math.max(4, Math.round(fontSize * 0.11));
        lines.push(
          `Dialogue: 0,${startStr},${endStr},NeonGlow,,0,0,0,,{\\blur${blur}}${content}`
        );
        lines.push(
          `Dialogue: 1,${startStr},${endStr},NeonCore,,0,0,0,,${content}`
        );
      } else {
        lines.push(`Dialogue: 0,${startStr},${endStr},Main,,0,0,0,,${content}`);
      }
      continue;
    }

    for (let i = 0; i < words.length; i += 1) {
      const stepStart = i === 0 ? cue.start : Math.max(cue.start, words[i].start);
      const nextWord = words[i + 1];
      const stepEnd =
        i === words.length - 1
          ? cue.end
          : Math.max(stepStart + 0.04, Math.min(cue.end, nextWord.start));

      if (stepEnd <= stepStart) continue;

      const startStr = formatAssTime(stepStart);
      const endStr = formatAssTime(stepEnd);

      if (settings.styleId === "tiktok") {
        const rendered = words
          .map((w, idx) => {
            const txt = escapeAssText(transformWord(w.text));
            if (idx === i) {
              return `{\\1c${hexToAssInlineColor(activeHex)}\\3c${hexToAssInlineColor(outlineHex)}\\fscx108\\fscy108}${txt}{\\fscx100\\fscy100}`;
            }
            if (idx < i) {
              return `{\\1c${hexToAssInlineColor(activeHex)}\\3c${hexToAssInlineColor(outlineHex)}}${txt}`;
            }
            return `{\\1c${hexToAssInlineColor(baseHex)}\\3c${hexToAssInlineColor(outlineHex)}}${txt}`;
          })
          .join(" ");
        lines.push(`Dialogue: 0,${startStr},${endStr},Main,,0,0,0,,${rendered}`);
      } else if (settings.styleId === "minimal") {
        const rendered = words
          .map((w, idx) => {
            const txt = escapeAssText(transformWord(w.text));
            if (idx <= i) {
              return `{\\1c${hexToAssInlineColor(activeHex)}\\1a&H00&}${txt}`;
            }
            return `{\\1c${hexToAssInlineColor(baseHex)}\\1a&H4A&}${txt}`;
          })
          .join(" ");
        lines.push(`Dialogue: 0,${startStr},${endStr},Main,,0,0,0,,${rendered}`);
      } else {
        const blur = Math.max(5, Math.round(fontSize * 0.12));
        const glowText = words
          .map((w, idx) => {
            const txt = escapeAssText(transformWord(w.text));
            if (idx === i) {
              return `{\\blur${blur}\\1c${hexToAssInlineColor(glowHex)}\\3c${hexToAssInlineColor(glowHex)}\\3a&H28&\\fscx106\\fscy106}${txt}{\\fscx100\\fscy100}`;
            }
            return `{\\blur${blur}\\1c${hexToAssInlineColor(outlineHex)}\\3c${hexToAssInlineColor(outlineHex)}\\3a&H48&}${txt}`;
          })
          .join(" ");

        const coreText = words
          .map((w, idx) => {
            const txt = escapeAssText(transformWord(w.text));
            if (idx === i) {
              return `{\\1c${hexToAssInlineColor("#FFFFFF")}\\3c${hexToAssInlineColor(activeHex)}\\fscx106\\fscy106}${txt}{\\fscx100\\fscy100}`;
            }
            if (idx < i) {
              return `{\\1c${hexToAssInlineColor("#ECFEFF")}\\3c${hexToAssInlineColor(outlineHex)}}${txt}`;
            }
            return `{\\1c${hexToAssInlineColor(baseHex)}\\3c${hexToAssInlineColor(outlineHex)}}${txt}`;
          })
          .join(" ");

        lines.push(`Dialogue: 0,${startStr},${endStr},NeonGlow,,0,0,0,,${glowText}`);
        lines.push(`Dialogue: 1,${startStr},${endStr},NeonCore,,0,0,0,,${coreText}`);
      }
    }
  }

  return `${lines.join("\n")}\n`;
}
